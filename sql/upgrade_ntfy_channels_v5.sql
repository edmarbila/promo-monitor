begin;

create extension if not exists pgcrypto;

alter table public.tg_coupon_sites
  add column if not exists ntfy_topic text;

update public.tg_coupon_sites
set ntfy_topic =
  coalesce(
    nullif(
      left(
        trim(both '-' from regexp_replace(lower(store_slug), '[^a-z0-9]+', '-', 'g')),
        48
      ),
      ''
    ),
    'cupons'
  )
  || '-' || encode(gen_random_bytes(5),'hex')
where ntfy_topic is null or btrim(ntfy_topic) = '';

alter table public.tg_coupon_sites
  alter column ntfy_topic
  set default ('cupons-' || encode(gen_random_bytes(6),'hex'));

alter table public.tg_coupon_sites
  alter column ntfy_topic set not null;

alter table public.tg_coupon_sites
  drop constraint if exists tg_coupon_sites_ntfy_topic_check;

alter table public.tg_coupon_sites
  add constraint tg_coupon_sites_ntfy_topic_check
  check (ntfy_topic ~ '^[A-Za-z0-9_-]{1,64}$');

create table if not exists public.tg_notification_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  dedupe_key text not null,
  kind text not null check (kind in ('product','coupon')),
  topic text not null check (topic ~ '^[A-Za-z0-9_-]{1,64}$'),
  sent_at timestamptz not null default now(),
  expires_at timestamptz not null,
  unique(user_id, dedupe_key)
);

create index if not exists tg_notification_log_expiry_idx
  on public.tg_notification_log(expires_at);

-- Evita uma enxurrada ao atualizar: cupons que já estavam ativos
-- são considerados já conhecidos por mais 48 horas.
insert into public.tg_notification_log(
  user_id, dedupe_key, kind, topic, sent_at, expires_at
)
select
  c.user_id,
  encode(
    digest(
      'coupon|' ||
      lower(regexp_replace(btrim(c.store_name), '\\s+', ' ', 'g')) ||
      '|' ||
      upper(btrim(c.code)),
      'sha256'
    ),
    'hex'
  ),
  'coupon',
  s.ntfy_topic,
  now(),
  now() + interval '48 hours'
from public.tg_coupons c
join public.tg_coupon_sites s
  on s.user_id = c.user_id
 and lower(btrim(s.store_name)) = lower(btrim(c.store_name))
where c.active = true
  and c.code is not null
  and btrim(c.code) <> ''
on conflict (user_id, dedupe_key) do nothing;

alter table public.tg_notification_log enable row level security;
revoke all on public.tg_notification_log from anon, authenticated;

create or replace function public.tg_claim_notification(
  p_user_id uuid,
  p_dedupe_key text,
  p_kind text,
  p_topic text,
  p_ttl_hours integer
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_rows integer := 0;
  v_ttl integer := greatest(1, least(coalesce(p_ttl_hours, 24), 720));
begin
  delete from public.tg_notification_log
  where user_id = p_user_id
    and dedupe_key = p_dedupe_key
    and expires_at <= now();

  insert into public.tg_notification_log(
    user_id, dedupe_key, kind, topic, expires_at
  )
  values (
    p_user_id,
    p_dedupe_key,
    p_kind,
    p_topic,
    now() + make_interval(hours => v_ttl)
  )
  on conflict (user_id, dedupe_key) do nothing;

  get diagnostics v_rows = row_count;
  return v_rows > 0;
end;
$$;

revoke all on function public.tg_claim_notification(uuid,text,text,text,integer)
from public, anon, authenticated;
grant execute on function public.tg_claim_notification(uuid,text,text,text,integer)
to service_role;

create or replace function public.tg_cleanup_old_data()
returns void language plpgsql security definer set search_path = public as $$
begin
  delete from public.tg_occurrences
  where occurred_at < now() - interval '24 hours';

  delete from public.tg_coupons
  where last_seen_at < now() - interval '48 hours';

  delete from public.tg_notification_log
  where expires_at <= now();
end;
$$;

commit;
